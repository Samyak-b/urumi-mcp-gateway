#!/usr/bin/env bash
# Generates every secret the cluster needs and renders one Helm values file per release.
#
#   deploy/secrets/generated.env   random values; a key is created once and then kept, so re-running never
#                                  rotates a password that is already in use
#   deploy/secrets/<release>.yaml  the values for one Helm release, holding only the secrets that release uses
#
# Hand-filled values (the LLM key) come from .env (see .env.example). Everything under deploy/secrets/ is
# git-ignored; the charts themselves contain no secret values.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=deploy/secrets
GEN=$OUT/generated.env
umask 077          # new files readable by this user only
mkdir -p "$OUT"
touch "$GEN"

# ensure KEY VALUE: append KEY=VALUE unless KEY is already present.
ensure() { grep -q "^$1=" "$GEN" || echo "$1=$2" >>"$GEN"; }
rand() { openssl rand -hex 24; }

ensure STORE_DB_ROOT_PASSWORD "$(rand)"
ensure STORE_DB_PASSWORD "$(rand)"
ensure STORE_ADMIN_PASSWORD "$(rand)"
# WooCommerce REST API key for the MCP server (WooCommerce requires the ck_/cs_ prefixes).
ensure WOO_CONSUMER_KEY "ck_$(openssl rand -hex 20)"
ensure WOO_CONSUMER_SECRET "cs_$(openssl rand -hex 20)"
# Shared token: the MCP server checks it, the gateway presents it.
ensure WOO_MCP_TOKEN "$(rand)"
ensure NOTES_MCP_TOKEN "$(rand)"

# Read KEY=VALUE lines without executing the file: a generated or hand-edited file is data, not a script.
load() {
  [[ -f $1 ]] || return 0
  while IFS='=' read -r k v; do
    [[ $k =~ ^[A-Z_][A-Z0-9_]*$ ]] || continue
    printf -v "$k" '%s' "${v%$'\r'}"
  done <"$1"
}
load "$GEN"

# YAML-quote a value (single quotes, embedded quotes doubled).
q() { printf "'%s'" "${1//\'/\'\'}"; }

cat >"$OUT/store.yaml" <<EOF
# Generated by scripts/gen-secrets.sh. Do not edit or commit.
secrets:
  dbRootPassword: $(q "$STORE_DB_ROOT_PASSWORD")
  dbPassword: $(q "$STORE_DB_PASSWORD")
  adminPassword: $(q "$STORE_ADMIN_PASSWORD")
  wooConsumerKey: $(q "$WOO_CONSUMER_KEY")
  wooConsumerSecret: $(q "$WOO_CONSUMER_SECRET")
  mcpToken: $(q "$WOO_MCP_TOKEN")
EOF

cat >"$OUT/notes.yaml" <<EOF
# Generated by scripts/gen-secrets.sh. Do not edit or commit.
secrets:
  mcpToken: $(q "$NOTES_MCP_TOKEN")
EOF

echo "secrets ready in $OUT/ (generated.env keeps the values; re-running keeps them)"
